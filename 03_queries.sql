-- Display all records
SELECT * FROM AIRLINE;
SELECT * FROM AIRCRAFT;
SELECT * FROM AIRPORT;
SELECT * FROM FLIGHT;
SELECT * FROM FLIGHT_SCHEDULE;
SELECT * FROM PASSENGER;
SELECT * FROM BOOKING;
SELECT * FROM TICKET;

-- Passenger, flight, seat and fare details (JOIN)
SELECT
    PASSENGER.Name,
    FLIGHT.Flight_Number,
    FLIGHT_SCHEDULE.Flight_Date,
    TICKET.Seat_Number,
    TICKET.Fare
FROM TICKET
JOIN BOOKING
ON TICKET.Booking_ID = BOOKING.Booking_ID
JOIN PASSENGER
ON BOOKING.Passenger_ID = PASSENGER.Passenger_ID
JOIN FLIGHT_SCHEDULE
ON TICKET.Schedule_ID = FLIGHT_SCHEDULE.Schedule_ID
JOIN FLIGHT
ON FLIGHT_SCHEDULE.Flight_ID = FLIGHT.Flight_ID;
